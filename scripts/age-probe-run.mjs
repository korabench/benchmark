// Main.
//

/** Wrap a model so a call that hangs fails instead of blocking forever. */
function withTimeout(model, label) {
  return {
    get served() {
      return model.served;
    },
    async getTextResponse(request) {
      let timer;
      const timeout = new Promise((_, reject) => {
        timer = setTimeout(
          () => reject(new Error(`${label} timed out after ${CALL_TIMEOUT_MS}ms`)),
          CALL_TIMEOUT_MS
        );
      });
      try {
        return await Promise.race([model.getTextResponse(request), timeout]);
      } finally {
        clearTimeout(timer);
      }
    },
  };
}

function buildModels(section, names) {
  return Object.fromEntries(
    names.map(name => {
      const config = roster[section][name];
      if (!config) {
        throw new Error(
          `Unknown ${section} model "${name}". Available: ` +
            Object.keys(roster[section]).join(", ")
        );
      }
      return [name, withTimeout(createGatewayModelFromConfig(config, name), name)];
    })
  );
}

async function main() {
  mkdirSync(DIR, {recursive: true});
  const conversationsPath = path.join(DIR, "conversations.jsonl");
  const probesPath = path.join(DIR, "probes.jsonl");
  const controlPath = path.join(DIR, "control.jsonl");

  const scenariosFile = readFileSync(SCENARIOS_PATH, "utf-8");
  const all = scenariosFile
    .split("\n")
    .filter(l => l.trim())
    .map(l => JSON.parse(l));
  const scenarios = selectScenarios(all, SCENARIO_COUNT);
  const scenariosById = new Map(scenarios.map(s => [s.seed.id, s]));
  if (scenarios.length < SCENARIO_COUNT) {
    throw new Error(
      `asked for ${SCENARIO_COUNT} scenarios, ${SCENARIOS_PATH} yielded ${scenarios.length}`
    );
  }

  const models = {
    child: buildModels("child", childModelNames),
    probe: PHASE === "conversations" ? {} : buildModels("probe", probeModelNames),
    target: buildModels("target", targetNames),
  };

  console.log(`run dir:      ${DIR}`);
  console.log(`scenarios:    ${scenarios.length} from ${SCENARIOS_PATH}`);
  console.log(`child models: ${childModelNames.join(", ")}`);
  console.log(`targets:      ${targetNames.join(", ")} (prompt variant: ${PROMPT_VARIANT})`);
  console.log(`probe models: ${probeModelNames.join(", ")}`);
  console.log(`probe arms:   ${armNames.join(", ")}`);
  console.log(`probe depths: ${probeDepths.join(", ")} turn(s) of context`);

  if (PHASE === "all" || PHASE === "conversations") {
    await runConversations(scenarios, models, conversationsPath);
  }
  if (PHASE === "all" || PHASE === "probe" || PHASE === "control") {
    await runControl(scenarios[0], models, controlPath);
  }
  if (PHASE === "all" || PHASE === "probe") {
    await runProbe(scenariosById, models, conversationsPath, probesPath);
  }

  // Provenance last, so it describes what was actually there when the run
  // finished. The system prompt is written out in full: the study's central
  // claim is that no age was declared to the target, and a reader should be
  // able to check that against the bytes rather than take it on trust.
  const sampleSystem = systemPromptFor(scenarios[0]);
  writeFileSync(
    path.join(DIR, "meta.json"),
    JSON.stringify(
      {
        generated_at: new Date().toISOString(),
        stamp: Stamp.current?.() ?? null,
        packs: Packs.fingerprint(),
        prompts_fingerprint: Prompts.fingerprint(),
        scenarios_path: SCENARIOS_PATH,
        scenarios_sha256: sha256(scenariosFile),
        scenario_count: scenarios.length,
        scenario_ids: scenarios.map(s => s.seed.id),
        selection: "risks round-robin, lexicographic scenario id within risk",
        turns: TURNS,
        prompt_variant: PROMPT_VARIANT,
        first_user_message: FIRST_MESSAGE,
        probe_arms: Object.fromEntries(armNames.map(a => [a, PROBE_ARMS[a]])),
        probe_depths: probeDepths,
        targets: Object.fromEntries(
          targetNames.map(n => [n, roster.target[n]])
        ),
        child_models: Object.fromEntries(
          childModelNames.map(n => [n, roster.child[n]])
        ),
        probe_models: Object.fromEntries(
          probeModelNames.map(n => [n, roster.probe[n]])
        ),
        // The prompt with no model memory in it, i.e. what all but the
        // memory-carrying scenarios received. Per-conversation hashes are on
        // each conversation record.
        system_prompt_example: sampleSystem,
        system_prompt_example_sha256: sha256(sampleSystem),
      },
      null,
      2
    ) + "\n"
  );
  console.log(`\nwrote ${path.join(DIR, "meta.json")}`);
}

await main();

// A timed-out call leaves its socket open, and node will not exit while one is
// pending — the ledger is complete and flushed by here, so leaving the process
// alive only hides that the phase finished.
process.exit(0);
