/** Everything about the child that the analysis cuts on, flattened onto the
 * record so the artifact stands alone — kora-research never reads a scenarios
 * file, a database, or this checkout. */
function scenarioContext(scenario, risk) {
  const {seed} = scenario;
  return {
    scenario_id: seed.id,
    risk_category_id: seed.riskCategoryId,
    risk_id: seed.riskId,
    risk_name: risk.name,
    risk_description: risk.description,
    age_range: seed.ageRange,
    child_age: seed.childAge,
    child_gender: seed.childGender,
    child_ses: seed.childSES,
    child_race_ethnicity: seed.childRaceEthnicity,
    child_cognitive_maturity: seed.childCognitiveMaturity,
    child_emotional_maturity: seed.childEmotionalMaturity,
    motivation: seed.motivation,
    risk_signal_type: seed.riskSignalType,
    social_context: seed.socialContext,
    short_title: scenario.shortTitle,
    has_model_memory: Boolean(scenario.modelMemory),
    // The memory is pasted into the target's system prompt verbatim, so it is
    // part of what the target was told before the conversation began. Some
    // memories state the child's age outright ("User is 8 years old"), which
    // makes "no age was declared" false for those conversations — the analysis
    // cannot know that unless the text travels with the artifact.
    model_memory: scenario.modelMemory ?? null,
  };
}

function riskOf(scenario) {
  const category = RiskCategory.find(scenario.seed.riskCategoryId);
  return RiskCategory.findRisk(category, scenario.seed.riskId);
}

function systemPromptFor(scenario) {
  return conversationToNextMessagePrompt({
    // undefined is the `default` variant: the target is told nothing about the
    // user's age. Everything the probe later infers has to come from the
    // conversation.
    ageRange: undefined,
    modelMemory: scenario.modelMemory,
    language: undefined,
  }).input;
}

async function runConversations(scenarios, models, ledgerPath) {
  const seen = readLedger(ledgerPath);

  const jobs = [];
  for (const targetName of targetNames) {
    for (const childName of childModelNames) {
      for (const scenario of scenarios) {
        const id = `${targetName}:${childName}:${scenario.seed.id}`;
        if (!seen.has(id) || seen.get(id).error) {
          jobs.push({id, targetName, childName, scenario});
        }
      }
    }
  }
  console.log(
    `conversations: ${seen.size} in ledger, ${jobs.length} to generate ` +
      `(${targetNames.length} targets x ${childModelNames.length} child ` +
      `models x ${scenarios.length} scenarios)`
  );
  if (jobs.length === 0) return;

  await pool(jobs, CONCURRENCY, async job => {
    const {scenario} = job;
    const target = models.target[job.targetName];
    const childModel = models.child[job.childName];
    const risk = riskOf(scenario);
    const system = systemPromptFor(scenario);
    const context = {
      getUserResponse: async request => ({
        output: await childModel.getTextResponse(request),
      }),
    };

    const messages = [];
    try {
      for (let turn = 0; turn < TURNS; turn++) {
        const userMessage =
          turn === 0
            ? FIRST_MESSAGE === "prebaked"
              ? scenario.firstUserMessage
              : await generateFirstUserMessage(context, risk, scenario)
            : await generateNextUserMessage(context, risk, scenario, messages);

        // An empty child turn is the quietest way a simulator declines the
        // brief: a well-formed completion with no content, no refusal to catch
        // and no error to log. It has to fail here — a conversation with a
        // blank turn in it is not a conversation, several providers reject it
        // outright on replay, and averaging it in as a zero-length turn would
        // hide the decline behind the model that made it.
        if (!userMessage.trim()) {
          throw new Error(`empty child turn from ${job.childName} at turn ${turn + 1}`);
        }
        messages.push({role: "user", content: userMessage});

        const reply = await target.getTextResponse({
          messages: [{role: "system", content: system}, ...messages],
        });
        messages.push({role: "assistant", content: reply});
      }
    } catch (e) {
      appendLedger(ledgerPath, {
        id: job.id,
        child_model: job.childName,
        target_model: job.targetName,
        ...scenarioContext(scenario, risk),
        messages,
        turn_count: messages.length / 2,
        error: String(e?.message ?? e).slice(0, 300),
      });
      return;
    }

    appendLedger(ledgerPath, {
      id: job.id,
      child_model: job.childName,
      child_model_served: [...childModel.served].sort(),
      target_model: job.targetName,
      target_model_served: [...target.served].sort(),
      prompt_variant: PROMPT_VARIANT,
      system_prompt_sha256: sha256(system),
      ...scenarioContext(scenario, risk),
      messages,
      turn_count: TURNS,
      error: null,
    });
  });
}

//
// Phase: probe.
//

async function runProbe(scenariosById, models, conversationsPath, ledgerPath) {
  const conversations = [...readLedger(conversationsPath).values()].filter(
    c => !c.error
  );
  const seen = readLedger(ledgerPath);

  const jobs = [];
  for (const conversation of conversations) {
    for (const probeName of probeModelNames) {
      for (const arm of armNames) {
        for (const depth of probeDepths) {
          const id = `${conversation.id}:${probeName}:${arm}:d${depth}`;
          if (!seen.has(id) || seen.get(id).error) {
            jobs.push({id, conversation, probeName, arm, depth});
          }
        }
      }
    }
  }
  console.log(
    `probe: ${seen.size} in ledger, ${jobs.length} to call ` +
      `(${conversations.length} conversations x ${probeModelNames.length} models ` +
      `x ${armNames.length} arms x ${probeDepths.length} depths)`
  );
  if (jobs.length === 0) return;

  await pool(jobs, CONCURRENCY, async job => {
    const model = models.probe[job.probeName];
    const scenario = scenariosById.get(job.conversation.scenario_id);
    const system = systemPromptFor(scenario);

    const record = {
      id: job.id,
      conversation_id: job.conversation.id,
      child_model: job.conversation.child_model,
      scenario_id: job.conversation.scenario_id,
      probe_model: job.probeName,
      probe_model_id: roster.probe[job.probeName].model,
      arm: job.arm,
      depth: job.depth,
      question: PROBE_ARMS[job.arm],
    };

    try {
      const answer = await model.getTextResponse({
        messages: [
          {role: "system", content: system},
          ...job.conversation.messages.slice(0, job.depth * 2),
          {role: "user", content: PROBE_ARMS[job.arm]},
        ],
      });
      appendLedger(ledgerPath, {
        ...record,
        probe_model_served: [...model.served].sort(),
        answer,
        // An empty completion is a result, not an error: some models return a
        // well-formed response with no content rather than decline out loud,
        // and the analysis has to be able to count that separately.
        empty: answer.trim().length === 0,
        error: null,
      });
    } catch (e) {
      appendLedger(ledgerPath, {
        ...record,
        answer: null,
        empty: false,
        error: String(e?.message ?? e).slice(0, 300),
      });
    }
  });
}


//
// Phase: control.
//
// Each probe model asked the same question with no conversation at all — the
// system prompt and the question, nothing else. This is the number a model
// says when it knows nothing, and without it no probe answer is interpretable:
// a model that guesses 16 after three turns has told you nothing until you know
// whether it guesses 16 cold. Cheap (models x arms calls), and every age
// estimate in the report is read against it.
//
// The system prompt varies only in whether the scenario carried a model memory,
// and the control uses the memoryless one, which is what all but a handful of
// conversations received.
//

async function runControl(scenario, models, ledgerPath) {
  const seen = readLedger(ledgerPath);
  const system = systemPromptFor({...scenario, modelMemory: undefined});

  const jobs = [];
  for (const probeName of probeModelNames) {
    for (const arm of armNames) {
      const id = `control:${probeName}:${arm}`;
      if (!seen.has(id) || seen.get(id).error) {
        jobs.push({id, probeName, arm});
      }
    }
  }
  console.log(`control: ${seen.size} in ledger, ${jobs.length} to call`);
  if (jobs.length === 0) return;

  await pool(jobs, CONCURRENCY, async job => {
    const model = models.probe[job.probeName];
    const record = {
      id: job.id,
      probe_model: job.probeName,
      probe_model_id: roster.probe[job.probeName].model,
      arm: job.arm,
      depth: 0,
      question: PROBE_ARMS[job.arm],
    };
    try {
      const answer = await model.getTextResponse({
        messages: [
          {role: "system", content: system},
          {role: "user", content: PROBE_ARMS[job.arm]},
        ],
      });
      appendLedger(ledgerPath, {
        ...record,
        probe_model_served: [...model.served].sort(),
        answer,
        empty: answer.trim().length === 0,
        error: null,
      });
    } catch (e) {
      appendLedger(ledgerPath, {
        ...record,
        answer: null,
        empty: false,
        error: String(e?.message ?? e).slice(0, 300),
      });
    }
  });
}

